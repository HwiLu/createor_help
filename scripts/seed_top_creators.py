def profile_url(platform: Platform, username: str) -> str:
    kw = urllib.parse.quote(username)
    return {
        Platform.XIAOHONGSHU: f"https://www.xiaohongshu.com/search_result?keyword={kw}",
        Platform.DOUYIN: f"https://www.douyin.com/search/{kw}",
        Platform.BILIBILI: f"https://search.bilibili.com/all?keyword={kw}",
        Platform.WECHAT_OFFICIAL_ACCOUNT: f"https://weixin.sogou.com/weixin?type=1&query={kw}",
        Platform.WECHAT_CHANNEL: f"https://weixin.sogou.com/weixin?type=2&query={kw}",
    }.get(platform, f"https://www.baidu.com/s?wd={kw}")


def main() -> None:
    Base.metadata.create_all(bind=engine)

    db = SessionLocal()
    try:
        db.query(TopCreator).delete()
        for platform, category, username, nickname, follower_count in CREATORS:
            ranked = sorted(
                [c for c in CREATORS if c[0] == platform and c[1] == category],
                key=lambda x: x[4],
                reverse=True,
            )
            rank = next(i + 1 for i, c in enumerate(ranked) if c[2] == username)
            creator = TopCreator(
                platform=platform.value,
                category=category.value,
                username=username,
                nickname=nickname,
                avatar_url=None,
                profile_url=profile_url(platform, username),
                follower_count=follower_count,
                follower_display=follower_tier(follower_count),
                rank=rank,
                is_featured=True,
                status="ACTIVE",
            )
            db.add(creator)
        db.commit()
        total = db.query(TopCreator).count()
        print(f"[OK] 已导入 {total} 位优秀博主示例数据。")
    finally:
        db.close()


if __name__ == "__main__":
    main()
